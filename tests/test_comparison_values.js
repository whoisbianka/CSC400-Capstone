const assert = require('node:assert/strict');
const {highlights, format} = require('../degree_path/static/js/comparison-values.js');
assert.deepEqual(highlights([50000, 60000], 'higher'), ['', 'Highest earnings']);
assert.deepEqual(highlights([10000, 20000], 'lower'), ['Lowest cost', '']);
assert.deepEqual(highlights([0, 100], 'lower'), ['Lowest cost', '']);
assert.deepEqual(highlights([10, 10], 'higher'), ['Tie for best', 'Tie for best']);
assert.deepEqual(highlights([null, 100], 'lower'), ['', '']);
assert.deepEqual(highlights([100, undefined], 'higher'), ['', '']);
assert.deepEqual(highlights([.2, .8], null), ['', '']);
assert.deepEqual(highlights([NaN, 100], 'lower'), ['', '']);
assert.deepEqual(highlights([10, 30, 20], 'higher'), ['', 'Highest earnings', '']);
assert.deepEqual(highlights([10, 30, 30, 20], 'higher'), ['', 'Tie for best', 'Tie for best', '']);
assert.deepEqual(highlights([0, 10, 20, 0], 'lower'), ['Tie for best', '', '', 'Tie for best']);
assert.deepEqual(highlights([null, 10, 20, undefined], 'higher'), ['', '', 'Highest earnings', '']);
assert.deepEqual(highlights([10, 10, 20, 30], 'higher'), ['', '', '', 'Highest earnings']);
assert.deepEqual(highlights([null, undefined, 20, NaN], 'higher'), ['', '', '', '']);
assert.equal(format(null, 'money'), 'Not reported');
assert.equal(format(0, 'money'), '$0');
assert.equal(format(.625, 'percent'), '62.5%');
assert.equal(format([500, null], 'range'), 'Not reported');
assert.equal(format([500, 700], 'range'), '500–700');
console.log('Comparison formatting and 2–4 value ranking tests passed.');
